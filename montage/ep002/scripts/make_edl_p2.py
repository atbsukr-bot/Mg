def review(units):
    used, out = set(), []
    for u in units:
        u = dict(u)
        if u.get('ins', {}).get('id') == 'Chapter':
            continue
        if u['id'] in DROP_INS:
            u.pop('ins', None); u.pop('cap_on_insert', None)
        if u['id'] in PAPER:
            lead, props = PAPER[u['id']]
            u.pop('broll', None); u.pop('cap_on_insert', None)
            u['ins'] = dict(id='PaperScene', props=props, lead=lead)
        br = u.get('broll')
        if br and (br['src'] in BANNED or br['src'] in used):
            u.pop('broll')
        elif br:
            used.add(br['src'])
        if u['id'] == 'p2_m4' and not u.get('broll') and 'riyadh_highway.mp4' not in used:
            u['broll'] = dict(src='riyadh_highway.mp4', ss=2, look='night', lead=5.0, frame=False); used.add('riyadh_highway.mp4')
        if u['id'] in ('coffee', 'p2_z13'):        # owner's style: the subscribe reminder shows twice
            u['banner'] = 'اشترك في القناة وفعّل الجرس'
        if u['id'] == 'p2_e6':
            u.pop('broll', None)
            u['banner'] = APOLOGY
        out.append(u)
    return out, used


